type Substance = [name: string, latin: string, amount: number | null, unit: string | null];

export type SeedProduct = {
  name: string;
  line: string;
  form: string;
  substances: Substance[];
  atc: string;
  atcName: string;
  company: string;
  category: "A" | "B" | "D" | "E";
  sl: boolean;
  type: "original" | "generikum" | "biosimilar" | "komplementaer";
  narcotic?: "a" | "b" | "c";
  indication: string;
  packs: [quantity: number, unit: string][];
};

const S = (name: string, latin: string, amount: number | null = null, unit: string | null = null): Substance => [
  name,
  latin,
  amount,
  unit,
];

